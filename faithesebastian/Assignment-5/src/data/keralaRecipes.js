export function findKeralaRecipes(query) {
  const searchTerm = query.trim().toLocaleLowerCase()
  if (!searchTerm) return KERALA_RECIPES

  return KERALA_RECIPES.filter((recipe) => {
    const searchableText = [
      recipe.strMeal,
      recipe.strCategory,
      recipe.strTags,
      recipe.strDescription,
      ...Array.from({ length: 20 }, (_, index) => recipe[`strIngredient${index + 1}`]),
    ]
      .filter(Boolean)
      .join(' ')
      .toLocaleLowerCase()

    return searchableText.includes(searchTerm)
  })
}

export function findKeralaRecipeById(id) {
  return KERALA_RECIPES.find((recipe) => recipe.idMeal === id) ?? null
}
