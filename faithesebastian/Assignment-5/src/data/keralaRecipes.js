const makeRecipe = ({
  id,
  name,
  category,
  description,
  image,
  ingredients,
  instructions,
  tags,
}) => {
  const recipe = {
    idMeal: `kerala-${id}`,
    strMeal: name,
    strCategory: category,
    strArea: 'Kerala',
    strMealThumb: image,
    strTags: tags,
    strInstructions: instructions.join('\n'),
    strDescription: description,
  }

  ingredients.forEach(([ingredient, measure], index) => {
    const number = index + 1
    recipe[`strIngredient${number}`] = ingredient
    recipe[`strMeasure${number}`] = measure
  })

  return recipe
}

